import { test } from "node:test";
import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { createHash } from "node:crypto";
const root = new URL("../public/models/chemical-pilot-v1/", import.meta.url);
const manifest = JSON.parse(await readFile(new URL("manifest.json",root)));
const sha = data => createHash("sha256").update(data).digest("hex");
for(const model of manifest) test(`${model.id}: valid compact GLB, preserved textures, metres and bounded indices`, async()=>{
  const bytes=await readFile(new URL(`${model.id}.glb`,root));
  assert.equal(sha(bytes),model.sha256);
  assert.equal(bytes.readUInt32LE(0),0x46546c67);
  assert.equal(bytes.readUInt32LE(4),2);
  assert.equal(bytes.readUInt32LE(8),bytes.length);
  const jsonSize=bytes.readUInt32LE(12);
  const gltf=JSON.parse(bytes.subarray(20,20+jsonSize));
  const bin=bytes.subarray(28+jsonSize);
  assert.equal(gltf.buffers.length,1);
  assert(!gltf.buffers[0].uri);
  assert.equal(bin.length,gltf.buffers[0].byteLength);
  for(const v of gltf.bufferViews) assert((v.byteOffset??0)+v.byteLength<=bin.length);
  const primitive=gltf.meshes[0].primitives[0],position=gltf.accessors[primitive.attributes.POSITION],index=gltf.accessors[primitive.indices];
  assert.equal(index.count,model.triangles*3);
  assert(index.count<model.sourceTriangles*3*.1);
  assert.equal(gltf.accessors[primitive.attributes.NORMAL].count,position.count);
  assert.equal(gltf.accessors[primitive.attributes.TEXCOORD_0].count,position.count);
  const view=gltf.bufferViews[index.bufferView];
  const indices=new Uint32Array(bin.buffer,bin.byteOffset+view.byteOffset,index.count);
  assert(indices.every(i=>i<position.count));
  assert(Math.abs(position.min[1])<.01);
  for(let axis=0;axis<3;axis++) assert(Math.abs(position.max[axis]-position.min[axis]-model.dimensionsM[axis])<.001);
  assert.equal(gltf.images.length,3);
  gltf.images.forEach((image,i)=>{
    assert.equal(image.mimeType,"image/jpeg");assert(!image.uri);
    const v=gltf.bufferViews[image.bufferView];
    assert.equal(sha(bin.subarray(v.byteOffset,v.byteOffset+v.byteLength)),model.textureSha256[i]);
  });
  const original=await readFile(new URL(`assets/chemical-pilot-2026-10-20/models/${model.id}/${model.id}-source.glb`,new URL("../",import.meta.url)));
  assert.equal(sha(original),model.sourceSha256,"original source remains untouched");
});
