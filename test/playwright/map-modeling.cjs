/* eslint-disable @typescript-eslint/no-require-imports -- Runnable local browser acceptance check. */
require('tsx/cjs');
const { chromium, expect: baseExpect } = require('@playwright/test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const { createDefaultDefenseProject } = require('../../src/shared/lib/defense-project.ts');
const expect = baseExpect.configure({ timeout: 30000 });
const fixture = createDefaultDefenseProject();
fixture.projectId = 'map-modeling-test';
fixture.enterpriseId = 'modeling-object-a';
fixture.version = 1;
fixture.baseObject = { id: fixture.enterpriseId, name: 'Объект А — проверка связи', center: { lat: 55.75, lng: 37.62 } };
fixture.source = 'backend';
fixture.layers = [ { ...fixture.layers[0], id: 'local-layer', name: 'Площадка', code: 'ПЛ', geometryType: 'circle', geometry: {type: 'circle', center: fixture.baseObject.center, radiusM: 1000}, isActive: true } ];
fixture.activeLayerId = fixture.layers[0].id;
fixture.placedObjects = fixture.assetLibrary.slice(0, 2).map((asset, i) => ({id: `shared-placement-${i}`, assetId: asset.id, layerId: fixture.activeLayerId, quantity: i + 2, status: 'planned', coordinates: {lat: 55.75 + (i ? -.0005 : .0005), lng: 37.62 + (i ? -.001 : .001)}, createdAt: fixture.updatedAt, updatedAt: fixture.updatedAt}));
(async () => {
  const browser = await chromium.launch();
  try {
    const page = await browser.newPage({viewport: {width: 1440, height: 972}});
    const errors = [], writes = [];
    page.on('pageerror', error => errors.push(error.message));
    page.on('request', request => { if (request.url().includes('/api/') && !['GET','HEAD'].includes(request.method())) writes.push(request.url()); });
    await page.route('**/api/defense/projects/map-modeling-test', route => route.fulfill({json: fixture}));
    await page.route('**/api/v1/enterprises?**', route => route.fulfill({json: {items: [
      {id: fixture.enterpriseId, name: fixture.baseObject.name, latitude: 55.75, longitude: 37.62},
      {id: 'modeling-object-b', name: 'Объект Б — другой центр', latitude: 55.7505, longitude: 37.621}
    ], totalItems: 2}}));
    await page.goto('http://localhost:3000/prototype?view=gis&projectId=map-modeling-test');
    await expect(page.getByLabel('Выбрать объект защиты')).toHaveValue(fixture.enterpriseId);
    await page.getByRole('button', {name: 'Ввести координаты', exact: true}).first().click();
    await page.getByLabel('Широта', {exact:true}).fill('55.7502');
    await page.getByLabel('Долгота', {exact:true}).fill('37.6202');
    await page.getByRole('button', {name:'Разместить',exact:true}).click();
    await expect(page.getByLabel('Широта', {exact:true})).toHaveCount(0);
    await page.getByRole('button', {name: 'К объекту', exact: true}).click();
    const camera = page.locator('[data-map-zoom]');
    const targetZoom = Math.log2(40075016.686 * Math.cos(55.75 * Math.PI / 180) / (512 * 100 * .0254 / 96));
    await expect.poll(async () => Number(await camera.getAttribute('data-map-zoom'))).toBeCloseTo(targetZoom, 5);
    await expect(camera).toHaveAttribute('data-map-latitude', '55.75');
    await page.getByRole('button', {name: 'К Монте-Карло', exact: true}).click();
    const root = page.locator('[data-mass-workspace]');
    await expect(root).toHaveAttribute('data-base-object-id', fixture.enterpriseId);
    await expect(root).toHaveAttribute('data-project-id', fixture.projectId);
    await expect(root.getByRole('button', {name:'Пуск', exact:true})).toBeEnabled();
    await expect(root.locator('[data-project-placement]')).toHaveCount(3);
    await expect(root.locator('[data-project-placement="shared-placement-0"] [data-tactical-symbol="aa-gun"]')).toHaveCount(1);
    await expect(root.locator('[data-project-placement="shared-placement-1"] [data-tactical-symbol="aa-machine-gun"]')).toHaveCount(1);
    await expect(root.locator('[data-view]').getByText(fixture.baseObject.name, {exact:true})).toHaveCount(0);
    await root.getByRole('button',{name:'Приблизить к объекту',exact:true}).click();
    await expect(root).toHaveAttribute('data-time-ms', '0');
    const placementName = `Средство: ${fixture.assetLibrary[0].name}, 2 шт.`;
    await root.getByRole('button', {name:placementName, exact:true}).click();
    fs.mkdirSync('output/playwright/map-modeling',{recursive:true});
    await page.screenshot({path:'output/playwright/map-modeling/bim-project-3d.png'});
    await root.getByRole('button', {name:'2D', exact:true}).click();
    const focusedWidth = Number((await root.getByRole('img', {name: /2D:/}).getAttribute('viewBox')).split(' ')[2]);
    assert.ok(focusedWidth > 450 && focusedWidth < 460, 'BIM close-up should span about 458 metres');
    await expect(root.locator('[data-enterprise-model="factory-campus@1"] [data-object-id]')).toHaveCount(4);
    await expect(root.locator('[data-view]').getByText(fixture.baseObject.name, {exact:true})).toHaveCount(0);
    await expect(root.locator('[data-project-placement]')).toHaveCount(3);
    await expect(root.locator('[data-project-placement="shared-placement-0"] [data-tactical-symbol="aa-gun"]')).toHaveCount(1);
    await expect(root.locator('[data-project-placement="shared-placement-1"] [data-tactical-symbol="aa-machine-gun"]')).toHaveCount(1);
    const east = Number(await root.locator('[data-project-placement="shared-placement-0"]').getAttribute('data-x-m'));
    assert.ok(Math.abs(east - .001 * 111320 * Math.cos(55.75 * Math.PI / 180)) < .00001);
    await root.getByRole('button', {name:'К следующему срабатыванию', exact:true}).click();
    await expect(root.locator('[data-finished]')).toHaveText('1');
    await expect(root.locator('[data-protection-zone] circle')).toHaveAttribute('r','600');
    await root.getByRole('button',{name:'Рассчитать пакет',exact:true}).click();
    await expect(root.locator('[data-batch-result]')).toBeVisible();
    fs.mkdirSync('output/playwright/map-modeling',{recursive:true});
    await page.screenshot({path:'output/playwright/map-modeling/modeling.png'});
    const menu=page.getByRole('navigation',{name:'Режим моделирования'});
    await menu.getByRole('button',{name:'Предприятие',exact:true}).click();
    await expect(page.locator('[data-project-overview]')).toHaveAttribute('data-project-overview',fixture.enterpriseId);
    await expect(page.locator('[data-project-overview] [data-project-placement]')).toHaveCount(3);
    await expect(page.locator('[data-project-overview] [data-tactical-symbol]')).toHaveCount(3);
    await page.locator('[data-project-overview]').getByRole('button',{name:'2D',exact:true}).click();
    await expect(page.locator('[data-project-overview] [data-enterprise-model="factory-campus@1"] [data-object-id]')).toHaveCount(4);
    await page.getByTitle('Карта', {exact: true}).click();
    await expect(page.getByLabel('Выбрать объект защиты')).toHaveValue(fixture.enterpriseId);
    await page.getByLabel('Выбрать объект защиты').selectOption('modeling-object-b');
    await page.getByRole('button',{name:'К Монте-Карло',exact:true}).click();
    await expect(root).toHaveAttribute('data-base-object-id','modeling-object-b');
    await root.getByRole('button',{name:'2D',exact:true}).click();
    await expect(root.locator('[data-project-placement]')).toHaveCount(3);
    await expect(root.locator('[data-project-placement="shared-placement-0"] [data-tactical-symbol="aa-gun"]')).toHaveCount(1);
    await expect(root.locator('[data-project-placement="shared-placement-1"] [data-tactical-symbol="aa-machine-gun"]')).toHaveCount(1);
    await expect(root.locator('[data-project-object]')).toHaveAttribute('data-project-object','modeling-object-b');
    assert.ok(Math.abs(Number(await root.locator('[data-project-placement="shared-placement-0"]').getAttribute('data-x-m'))) < .00001);
    await page.setViewportSize({width:375,height:812});
    await page.getByRole('link',{name:'Карта',exact:true}).click();
    await expect(page.getByLabel('Выбрать объект защиты')).toBeVisible();
    await page.screenshot({path:'output/playwright/map-modeling/map-mobile-before.png'});
    await page.getByRole('button',{name:'К объекту',exact:true}).click();
    await expect(page.getByLabel('Масштаб 1:100',{exact:true})).toBeAttached();
    await page.screenshot({path:'output/playwright/map-modeling/map-mobile.png'});
    await page.getByRole('button',{name:'К Монте-Карло',exact:true}).click();
    await expect(root).toHaveAttribute('data-base-object-id','modeling-object-b');
    await root.getByRole('button',{name:'2D',exact:true}).click();
    await expect(root.locator('[data-project-placement]')).toHaveCount(3);
    await expect(root.locator('[data-project-placement="shared-placement-0"] [data-tactical-symbol="aa-gun"]')).toHaveCount(1);
    await expect(root.locator('[data-project-placement="shared-placement-1"] [data-tactical-symbol="aa-machine-gun"]')).toHaveCount(1);
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
    await page.screenshot({path:'output/playwright/map-modeling/modeling-mobile.png'});
    assert.deepEqual(writes, []);
    assert.deepEqual(errors, []);
    console.log('PASS: 1:100 focus, new GIS placement and existing configuration shared in 2D/3D and enterprise view, Monte Carlo boundary/batch, map return and changed object, no writes/errors');
  } finally { await browser.close(); }
})().catch(error => {console.error(error);process.exitCode=1;});
